package Clases;

public class Premio {
     int vuelto;
    String premio;

    public Premio(int v, String p) {
        this.vuelto = v;
        this.premio = p;
    }

    public int getVuelto() {
        return this.vuelto;
    }

    public String getPremio() {
        return this.premio;
    }


    
}
